const BY_KEY = new Map(METERS.map((meter) => [meter.key, meter]));

export function getMeter(key: string): Meter | null {
  return BY_KEY.get(key as MeterKey) ?? null;
}

export function isMeterKey(value: string): value is MeterKey {
  return BY_KEY.has(value as MeterKey);
}

export type MeterUsage = {
  meterKey: MeterKey;
  quantity: number;
  included: number;
  billable: number;
  unitPricePence: number;
  amountPence: number;
};

/**
 * Price one meter's consumption for a month.
 *
 * Overage is charged on whole units above the allowance. The allowance and rate
 * are taken from the meter at the moment this is called and then frozen onto
 * the counter row by the caller — this function never reads them again.
 */
export function priceUsage(meter: Meter, quantity: number): MeterUsage {
  const safeQuantity = Math.max(0, Math.trunc(quantity));
  const billable = Math.max(0, safeQuantity - meter.includedPerMonth);

  return {
    meterKey: meter.key,
    quantity: safeQuantity,
    included: meter.includedPerMonth,
    billable,
    unitPricePence: meter.overagePencePerUnit,
    // Integer pence throughout: unit price is already an integer and billable
    // is a whole count, so this cannot accumulate a fractional penny.
    amountPence: billable * meter.overagePencePerUnit,
  };
}

/** "1,204 emails" — pluralised, thousands-separated. */
export function formatUsage(meter: Meter, quantity: number): string {
  const plural = quantity === 1 ? meter.unit : `${meter.unit}s`;
  return `${quantity.toLocaleString("en-GB")} ${plural}`;
}
