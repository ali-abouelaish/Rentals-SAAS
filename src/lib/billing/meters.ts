/**
 * Metered usage: what gets counted, what is included, what overage costs.
 *
 * Same convention as the integration catalogue and the envelope packs — the
 * catalogue is code, the database holds only what was consumed. A meter's rate
 * and allowance are frozen onto the counter row at rollup, so changing a number
 * here re-prices only months measured afterwards.
 *
 * Dependency-free on purpose: no `server-only`, no database client, so it loads
 * under `node --test` and can be imported from a client component to render an
 * agency's own usage. Matches `packs.ts` and `rates.ts`.
 *
 * ADDING A METER
 *   1. Add the entry here.
 *   2. Add its count query to `countMeter` in src/lib/cron/usageRollup.ts.
 *   3. That is all — rollup, invoicing and the admin views are driven from this
 *      list.
 */

export type MeterKey =
  | "emails_sent"
  | "ai_messages"
  | "deposits_registered"
  | "sms_sent";

export type Meter = {
  key: MeterKey;
  name: string;
  /** Singular unit, for "1,204 emails". */
  unit: string;
  /** One line explaining exactly what is counted — shown to the agency. */
  description: string;
  /** Included each month before overage applies. */
  includedPerMonth: number;
  /**
   * Pence per unit beyond the allowance.
   *
   * ZERO FOR EVERY METER IN V1, and that is the point rather than an omission.
   * Counting usage and charging for it are separate decisions: this ships the
   * measurement so there is data to price against, while a zero rate produces
   * no invoice line at all — nothing an agency sees or pays changes until a
   * real number is set here. `VAT_RATE_BPS` in rates.ts works the same way.
   */
  overagePencePerUnit: number;
};

